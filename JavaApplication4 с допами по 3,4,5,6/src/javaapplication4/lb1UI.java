    private void loadFromTextFile(File file) {
    LinkedList<RecIntegral> tempList = new LinkedList<>();

    try (BufferedReader reader = new BufferedReader(new FileReader(file))) {
        String line;

        while ((line = reader.readLine()) != null) {
            if (line.trim().isEmpty()) continue;

            String[] parts = line.split(";");
            if (parts.length < 4) {
                throw new IOException("Некорректный формат строки: " + line);
            }

            double lower = Double.parseDouble(parts[0]);
            double upper = Double.parseDouble(parts[1]);
            double step = Double.parseDouble(parts[2]);

            RecIntegral rec = new RecIntegral(lower, upper, step);

            if (!parts[3].isEmpty()) {
                rec.setResult(Double.parseDouble(parts[3]));
            }

            tempList.add(rec);
        }

        records.clear();
        records.addAll(tempList);
        refreshTable();

        JOptionPane.showMessageDialog(this,
                "Данные успешно загружены из текстового файла.",
                "Успех",
                JOptionPane.INFORMATION_MESSAGE);

    } catch (IOException | NumberFormatException | InvalidRangeException e) {
        JOptionPane.showMessageDialog(this,
                "Ошибка загрузки текстового файла: " + e.getMessage(),
                "Ошибка",
                JOptionPane.ERROR_MESSAGE);
    }
}
