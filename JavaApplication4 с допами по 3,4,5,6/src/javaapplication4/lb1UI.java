private void startServer(int port) {
    System.out.println("Запуск UDP-сервера регистрации");

    if (serverRunning) {
        System.out.println("Сервер уже запущен");
        return;
    }

    Thread serverThread = new Thread(() -> {
        try {
            registerSocket = new java.net.DatagramSocket(port);
            taskSocket = new java.net.DatagramSocket(TASK_PORT);
            serverRunning = true;

            System.out.println("REGISTER socket запущен на порту " + port);
            System.out.println("TASK/RESULT socket запущен на порту " + TASK_PORT);

            while (serverRunning) {
                byte[] buffer = new byte[1024];
                DatagramPacket packet = new DatagramPacket(buffer, buffer.length);
                registerSocket.receive(packet);

                String message = new String(
                        packet.getData(),
                        0,
                        packet.getLength(),
                        java.nio.charset.StandardCharsets.UTF_8
                );

                System.out.println("REGISTER socket получил: " + message);

                if ("REGISTER".equals(message)) {
                    UDPClientInfo client = new UDPClientInfo(packet.getAddress(), packet.getPort());

                    synchronized (clients) {
                        if (!clients.contains(client)) {
                            clients.add(client);
                            System.out.println("Клиент зарегистрирован: " + client);
                        } else {
                            System.out.println("Клиент уже зарегистрирован: " + client);
                        }
                    }
                }
            }
        } catch (Exception e) {
            if (serverRunning) {
                System.out.println("Ошибка в startServer:");
                e.printStackTrace();
            }
        }
    });

    serverThread.start();
    System.out.println("Поток регистрации запущен");
}
private double calculateDistributed(double lower, double upper, double step) throws Exception {    java.util.List<UDPClientInfo> activeClients;

    synchronized (clients) {
        activeClients = new java.util.ArrayList<>(clients);
    }

    System.out.println("Клиентов для вычисления: " + activeClients.size());

    if (activeClients.isEmpty()) {
        throw new Exception("Нет подключенных клиентов.");
    }

    int clientCount = activeClients.size();
    double intervalLength = upper - lower;
    double partLength = intervalLength / clientCount;

    double start = lower;

    // Отправка TASK всем клиентам через отдельный сокет
    for (int i = 0; i < clientCount; i++) {
        double end = (i == clientCount - 1) ? upper : start + partLength;

        String taskMessage = "TASK;" + start + ";" + end + ";" + step;
        byte[] taskData = taskMessage.getBytes(StandardCharsets.UTF_8);

        UDPClientInfo client = activeClients.get(i);

        DatagramPacket packet = new DatagramPacket(
                taskData,
                taskData.length,
                client.getAddress(),
                client.getPort()
        );

        System.out.println("Отправка TASK клиенту " + client + ": " + taskMessage);
        taskSocket.send(packet);

        start = end;
    }

    // Ждём RESULT только на taskSocket
    taskSocket.setSoTimeout(10000);

    double total = 0.0;
    int receivedResults = 0;

    while (receivedResults < clientCount) {
        try {
            byte[] buffer = new byte[1024];
            DatagramPacket packet = new DatagramPacket(buffer, buffer.length);

            System.out.println("Ожидание RESULT... " + (receivedResults + 1) + "/" + clientCount);
            taskSocket.receive(packet);

            String message = new String(
                    packet.getData(),
                    0,
                    packet.getLength(),
                    StandardCharsets.UTF_8
            );

            System.out.println("TASK socket получил: " + message +
                    " от " + packet.getAddress().getHostAddress() + ":" + packet.getPort());

            if (message.startsWith("RESULT;")) {
                String[] parts = message.split(";");
                double partial = Double.parseDouble(parts[1]);
                total += partial;
                receivedResults++;

                System.out.println("Частичный результат принят: " + partial);
            } else {
                System.out.println("Игнорируется сообщение: " + message);
            }

        } catch (java.net.SocketTimeoutException e) {
            throw new Exception("Истекло время ожидания ответов от клиентов.");
        }
    }

    taskSocket.setSoTimeout(0);

    System.out.println("Итоговый результат: " + total);
    return total;
}
    
