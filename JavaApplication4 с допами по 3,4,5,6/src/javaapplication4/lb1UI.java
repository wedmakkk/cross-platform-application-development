    private void refreshTable() {
    DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
    model.setRowCount(0);

    for (RecIntegral rec : records) {
        String resultStr = (rec.getResult() == null) ? "" : String.format("%.4f", rec.getResult());
        model.addRow(new Object[]{
            rec.getLower(),
            rec.getUpper(),
            rec.getStep(),
            resultStr
        });
    }
}
