    private void jButtonFillActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonFillActionPerformed
        // TODO add your handling code here:
        // Очищаем таблицу
    DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
    model.setRowCount(0);
    // Заполняем таблицу данными из коллекции
    for (RecIntegral rec : records) {
        String resultStr = (rec.getResult() == null) ? "" : String.format("%.4f", rec.getResult());
        model.addRow(new Object[]{
            rec.getLower(),
            rec.getUpper(),
            rec.getStep(),
            resultStr
        });
    }
    }//GEN-LAST:event_jButtonFillActionPerformed

