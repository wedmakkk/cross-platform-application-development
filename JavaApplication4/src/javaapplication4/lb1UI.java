    private void jButtonAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddActionPerformed
        // TODO add your handling code here:
        try {
        String lowerStr = jTextField1.getText().trim();
        String upperStr = jTextField2.getText().trim();
        String stepStr = jTextField3.getText().trim();

        double lower = Double.parseDouble(lowerStr);
        double upper = Double.parseDouble(upperStr);
        double step = Double.parseDouble(stepStr);

        // Создание объекта с проверкой диапазона
        RecIntegral rec = new RecIntegral(lower, upper, step);
        records.add(rec);

        DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
        model.addRow(new Object[]{lower, upper, step, ""});

        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");

    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,
            "Пожалуйста, введите корректные числа (разделитель дробной части — точка).",
            "Ошибка ввода", JOptionPane.ERROR_MESSAGE);
    } catch (InvalidRangeException ex) {
        JOptionPane.showMessageDialog(this,
            ex.getMessage(),
            "Ошибка диапазона", JOptionPane.WARNING_MESSAGE);
    }
        
    }//GEN-LAST:event_jButtonAddActionPerformed

    private void jButtonDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteActionPerformed
        int selected = jTable2.getSelectedRow();
    if (selected == -1) {
        JOptionPane.showMessageDialog(this,
            "Выберите строку для удаления.",
            "Предупреждение", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Удаляем из коллекции
    records.remove(selected);

    // Удаляем из таблицы
    DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
    model.removeRow(selected);
        // TODO add your handling code here:
    }//GEN-LAST:event_jButtonDeleteActionPerformed

    private void jButtonCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCalculateActionPerformed
        int selected = jTable2.getSelectedRow();
    if (selected == -1) {
        JOptionPane.showMessageDialog(this,
            "Выберите строку для вычисления.",
            "Предупреждение", JOptionPane.WARNING_MESSAGE);
        return;
    }

    DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
    try {
        double lower = Double.parseDouble(model.getValueAt(selected, 0).toString());
        double upper = Double.parseDouble(model.getValueAt(selected, 1).toString());
        double step = Double.parseDouble(model.getValueAt(selected, 2).toString());

        RecIntegral rec = records.get(selected);
        // Проверка диапазона через сеттеры
        rec.setLower(lower);
        rec.setUpper(upper);
        rec.setStep(step);

        double result = rec.integrateSqrt(step, lower, upper);
        rec.setResult(result);

        model.setValueAt(String.format("%.4f", result), selected, 3);

    } catch (NumberFormatException | NullPointerException e) {
        JOptionPane.showMessageDialog(this,
            "Ошибка в данных строки.",
            "Ошибка", JOptionPane.ERROR_MESSAGE);
    } catch (InvalidRangeException ex) {
        JOptionPane.showMessageDialog(this,
            ex.getMessage(),
            "Ошибка диапазона", JOptionPane.WARNING_MESSAGE);
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this,
            e.getMessage(),
            "Ошибка", JOptionPane.ERROR_MESSAGE);
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_jButtonCalculateActionPerformed

